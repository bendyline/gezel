import { spawnSync } from 'node:child_process';
import { mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = fileURLToPath(new URL('..', import.meta.url));
const destination = resolve(
  mobile,
  'android/app/src/androidTest/assets/fixtures/deterministic-native.gguf',
);
const source = process.argv[2] || process.env.GEZEL_ANDROID_TEST_FIXTURE;
const temporary = `${destination}.partial`;
await mkdir(dirname(destination), { recursive: true });
try {
  if (source) {
    const input = resolve(source);
    const metadata = await stat(input);
    if (!metadata.isFile() || metadata.size > 1024 * 1024) {
      throw new Error('Expected the small deterministic GGUF generated by gezel-llama-tests.');
    }
    await writeFile(temporary, await readFile(input));
  } else {
    const executable = resolve(mobile, '../../native/mobile/.build/host/build/gezel-llama-tests');
    const result = spawnSync(executable, ['--write-fixture', temporary], { stdio: 'inherit' });
    if (result.error || result.status !== 0) {
      throw new Error(
        'Build native/mobile/build-llama.py host first, or pass the generated GGUF fixture path.',
        { cause: result.error },
      );
    }
  }
  const bytes = await readFile(temporary);
  if (bytes.length > 1024 * 1024 || bytes.subarray(0, 4).toString() !== 'GGUF') {
    throw new Error('Expected the small deterministic GGUF generated by gezel-llama-tests.');
  }
  await rename(temporary, destination);
  console.log(`Staged ${bytes.length} bytes in androidTest assets only: ${destination}`);
} finally {
  await rm(temporary, { force: true });
}
