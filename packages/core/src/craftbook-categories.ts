/**
 * Craftbook subject categories — *what kind of work is this recipe about?*
 *
 * This is a third axis, deliberately independent of the two that already
 * exist. `CraftbookRole` answers "where in a project's life does this fit?"
 * (starter / maintenance / general) and a project type's `craftbookTags`
 * answer "does this fit THIS project?". Neither of those splits a 250-book
 * catalog into shelves a person can browse: on a code project the role axis
 * collapses to two enormous piles, one of which ("General work") is mostly
 * recipes about writing, media, and household admin.
 *
 * Each category belongs to a family — `code`, `non-code`, or the `universal`
 * shelves that belong to neither — so a browser can separate "recipes for
 * working on software" from everything else with one grouping, then offer a
 * real breakdown inside each.
 */
export const CraftbookCategorySchema = z.enum([
  'code-build',
  'code-quality',
  'code-review',
  'code-data',
  'code-release',
  'code-ops',
  'code-docs',
  'writing',
  'media',
  'design',
  'marketing',
  'research',
  'business',
  'personal',
  'practice',
  'other',
]);
export type CraftbookCategory = z.infer<typeof CraftbookCategorySchema>;

export type CraftbookCategoryFamily = 'code' | 'non-code' | 'universal';

