const CATEGORY_WEIGHTS = new Map<CraftbookCategory, Map<string, number>>(
  (Object.entries(CATEGORY_TAGS) as [CraftbookCategory, (typeof CATEGORY_TAGS)['media']][]).map(
    ([category, { strong, weak }]) => {
      const weights = new Map<string, number>();
      for (const tag of weak) weights.set(tag, 1);
      for (const tag of strong) weights.set(tag, 3);
      return [category, weights];
    },
  ),
);

/** Scoring order; a tie goes to the category declared first. */
const SCORING_ORDER: readonly CraftbookCategory[] = [
  'code-review',
  'code-quality',
  'code-release',
  'code-ops',
  'code-data',
  'code-docs',
  'code-build',
  'media',
  'design',
  'marketing',
  'writing',
  'research',
  'business',
  'personal',
];

/**
 * Infer a category from a craftbook's tags. Only used when the catalog item
 * does not declare one — first-party content authors `category` explicitly, so
 * this is the floor under third-party and older manifests rather than the
 * mechanism the shipped shelves rely on.
 */
export function inferCraftbookCategory(tags: readonly string[] | undefined): CraftbookCategory {
  const seen = new Set<string>();
  for (const tag of tags ?? []) {
    const normalized = tag.toLowerCase().trim();
    if (normalized && !NEUTRAL_TAGS.has(normalized)) seen.add(normalized);
  }
  if (seen.size === 0) return 'other';
  let best: CraftbookCategory = 'other';
  let bestScore = 0;
  for (const category of SCORING_ORDER) {
    const weights = CATEGORY_WEIGHTS.get(category)!;
    let score = 0;
    for (const tag of seen) score += weights.get(tag) ?? 0;
    if (score > bestScore) {
      best = category;
      bestScore = score;
    }
  }
  return best;
}

/** The category a craftbook browser should shelve this manifest under. */
export function resolveCraftbookCategory(manifest: {
  category?: CraftbookCategory;
  tags?: readonly string[];
}): CraftbookCategory {
  return manifest.category ?? inferCraftbookCategory(manifest.tags);
}

/** Family lookup for a resolved category, for two-level shelf grouping. */
export function craftbookCategoryFamily(category: CraftbookCategory): CraftbookCategoryFamily {
  return CRAFTBOOK_CATEGORY_META.find((meta) => meta.id === category)?.family ?? 'universal';
}
