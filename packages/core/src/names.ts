/**
 * Roughly the share of generated gezels we want to land as non-binary.
 * Applied as a flat random flip on top of the name-derived gender — so a
 * "male" name has the same NB chance as a "female" one. Kept low so the
 * common case still feels natural; the user can override in the create
 * dialog when they want a specific shape.
 */
const NON_BINARY_RATE = 0.04;

const femaleNameSet = new Set(femaleNames);
const maleNameSet = new Set(maleNames);

/**
 * Pronoun string for a gezel's gender — `he/him`, `she/her`, `they/them`.
 * Used in system-prompt headers and when one gezel references another.
 */
export function pronounsForGender(gender: GezelGender): string {
  switch (gender) {
    case 'male':
      return 'he/him';
    case 'female':
      return 'she/her';
    case 'non-binary':
      return 'they/them';
  }
}

/**
 * Grammatical forms for referring to a gezel in prose.
 *
 * `gender` is optional because legacy gezels predate the persisted field.
 * Unknown assignments fall back to neutral they/them rather than guessing
 * from the gezel's name.
 */
export interface GezelPronounForms {
  subject: 'he' | 'she' | 'they';
  object: 'him' | 'her' | 'them';
  possessiveAdjective: 'his' | 'her' | 'their';
  possessive: 'his' | 'hers' | 'theirs';
  reflexive: 'himself' | 'herself' | 'themselves';
  presentBe: 'is' | 'are';
  presentHave: 'has' | 'have';
}

export function pronounFormsForGender(gender?: GezelGender): GezelPronounForms {
  switch (gender) {
    case 'male':
      return {
        subject: 'he',
        object: 'him',
        possessiveAdjective: 'his',
        possessive: 'his',
        reflexive: 'himself',
        presentBe: 'is',
        presentHave: 'has',
      };
    case 'female':
      return {
        subject: 'she',
        object: 'her',
        possessiveAdjective: 'her',
        possessive: 'hers',
        reflexive: 'herself',
        presentBe: 'is',
        presentHave: 'has',
      };
    case 'non-binary':
    case undefined:
      return {
        subject: 'they',
        object: 'them',
        possessiveAdjective: 'their',
        possessive: 'theirs',
        reflexive: 'themselves',
        presentBe: 'are',
        presentHave: 'have',
      };
  }
}

/**
 * Pick a random first name AND the gender that goes with it. Names are
 * drawn 50/50 from the gendered pools; then a flat NON_BINARY_RATE share
 * of generated gezels has their gender flipped to non-binary (the name
 * is kept). Callers that want gender derived from a pre-chosen name
 * should use {@link inferGenderForName} instead.
 */
export function pickRandomNameWithGender(): { name: string; gender: GezelGender } {
  const pickFemale = Math.random() < 0.5;
  const pool = pickFemale ? femaleNames : maleNames;
  const name = pool[Math.floor(Math.random() * pool.length)]!;
  if (Math.random() < NON_BINARY_RATE) {
    return { name, gender: 'non-binary' };
  }
  return { name, gender: pickFemale ? 'female' : 'male' };
}

