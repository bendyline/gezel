#!/usr/bin/env node
/**
 * Regenerate the scorecard barrel from the shard directory.
 *
 *   pnpm scorecard:barrel            # write it
 *   pnpm scorecard:barrel --check    # fail if stale (CI, via shards.test.ts)
 *
 * The barrel exists because ESM cannot glob: core loads its data through
 * static `import ... with { type: 'json' }`, which esbuild inlines into
 * `dist/index.js`, and esbuild has no `import.meta.glob`. A runtime directory
 * read is not an option either — core is imported by the UI and must stay
 * browser-safe with no fs.
 *
 * So the barrel is generated and committed, the same contract gilde's
 * exported schemas use. `--check` runs in CI because a forgotten regen would
 * silently DROP a sweep from the published table with no error anywhere —
 * the same failure mode as a manifest that build-index skips.
 *
 * Output is piped through Biome before being written or compared. Biome sorts
 * imports and wraps long ones, so a hand-rolled layout would drift out of
 * `pnpm lint` the moment a run id got long enough to wrap — and `--check`
 * would then fail forever with nothing actually wrong. Emit, format, compare.
 *
 * Import order is therefore Biome's (ascending path), which is fine because
 * it carries no meaning: `mergeShards` sorts runs by recency at load.
 *
 * Merge note: two branches that each add a sweep both add a line here. Ids
 * lead with the sweep date, so they usually sort to different positions and
 * git merges them cleanly; when they don't, rerun this script instead of
 * resolving by hand. That is the whole reason the DATA is not in this file.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(repoRoot, 'packages/core/src/scorecard/data');
const runsDir = join(dataDir, 'runs');
const barrelPath = join(dataDir, 'index.ts');

/** Mirror of shardImportName in packages/core/src/scorecard/shards.ts. */
const importName = (runId) => `run_${runId.replace(/[^A-Za-z0-9]/g, '_')}`;

function shardFiles() {
  return readdirSync(runsDir)
    .filter((name) => name.endsWith('.json'))
    .sort();
}

function render() {
  const files = shardFiles();
  const imports = files
    .map((file) => {
      const runId = file.replace(/\.json$/, '');
      return `import ${importName(runId)} from './runs/${file}' with { type: 'json' };`;
    })
    .join('\n');
  const entries = files
    .map((file) => `  ${importName(file.replace(/\.json$/, ''))} as unknown as ScorecardDataset,`)
    .join('\n');

  return `// GENERATED by scripts/gen-scorecard-barrel.mjs — do not edit by hand.
// Add a sweep by writing packages/core/src/scorecard/data/runs/<run-id>.json
// (the eval scorecard ingest does this for you), then run \`pnpm scorecard:barrel\`.
import type { ScorecardDataset } from '../schema.js';

${imports}

/** Every recorded sweep. Merged (and ordered by recency) by ../index.ts. */
export const RUN_SHARDS: ScorecardDataset[] = [
${entries}
];
`;
}

/** Apply the repo's own Biome rules so the generated file is lint-clean. */
function biomeFormat(path) {
  const biomeCli = createRequire(import.meta.url).resolve('@biomejs/biome/bin/biome');
  const run = spawnSync(
    process.execPath,
    [biomeCli, 'check', '--write', '--config-path', repoRoot, path],
    { cwd: repoRoot, encoding: 'utf8' },
  );
  if (run.error) throw new Error(`[scorecard-barrel] Biome failed: ${run.error.message}`);
  if (run.status !== 0) {
    const detail = run.stderr.trim() || run.stdout.trim();
    throw new Error(`[scorecard-barrel] Biome could not format the barrel:\n${detail}`);
  }
  return readFileSync(path, 'utf8');
}

const current = (() => {
  try {
    return readFileSync(barrelPath, 'utf8');
  } catch {
    return null;
  }
})();

if (process.argv.includes('--check')) {
  // Format a scratch copy beside the real file so the comparison is against
  // the same bytes a write would have produced.
  const probe = join(dataDir, '.barrel-check.tmp.ts');
  let next;
  try {
    writeFileSync(probe, render());
    next = biomeFormat(probe);
  } finally {
    rmSync(probe, { force: true });
  }
  if (current !== next) {
    console.error('[scorecard-barrel] out of date — run `pnpm scorecard:barrel`.');
    console.error(`  shards: ${shardFiles().length} file(s) in ${runsDir}`);
    process.exit(1);
  }
  console.log(`[scorecard-barrel] up to date (${shardFiles().length} sweeps)`);
} else {
  writeFileSync(barrelPath, render());
  const written = biomeFormat(barrelPath);
  console.log(
    written === current
      ? `[scorecard-barrel] unchanged (${shardFiles().length} sweeps)`
      : `[scorecard-barrel] wrote ${barrelPath} (${shardFiles().length} sweeps)`,
  );
}
