#!/usr/bin/env node
// Writes packages/core/src/transform/molen-primers.generated.ts: the primers that teach a model
// Molen's authoring documents (film, game, data-only scene), quoted into the craftbook authoring
// notes so core takes no dependency on Molen. Source: the installed @bendyline/molen-stage when
// the service pins it, else the sibling molen checkout (MOLEN_DIR, default ../molen). Run after
// bumping the pin; `--check` fails when the snapshot differs from the source.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const out = join(repo, 'packages/core/src/transform/molen-primers.generated.ts');

async function fromPackage() {
  try {
    const req = createRequire(join(repo, 'packages/service/package.json'));
    // The package exports only `.`, so find its manifest from the entry file.
    const entry = req.resolve('@bendyline/molen-stage');
    let dir = dirname(entry);
    while (!existsSync(join(dir, 'package.json'))) dir = dirname(dir);
    const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const mod = await import(pathToFileURL(entry).href);
    return {
      source: `@bendyline/molen-stage@${version}`,
      film: mod.filmPrimer,
      game: mod.gamePrimer,
      scene: mod.scenePrimer,
    };
  } catch {
    return undefined;
  }
}

function fromCheckout() {
  const dir = resolve(repo, process.env.MOLEN_DIR ?? '../molen', 'packages/stage/primers');
  if (!existsSync(dir)) return undefined;
  const read = (name) => readFileSync(join(dir, `${name}.md`), 'utf8');
  return {
    source: 'the molen checkout (packages/stage/primers)',
    film: read('film'),
    game: read('game'),
    scene: read('scene'),
  };
}

const primers = (await fromPackage()) ?? fromCheckout();
if (primers === undefined) {
  console.error(
    'No @bendyline/molen-stage installed and no molen checkout at MOLEN_DIR (default ../molen).',
  );
  process.exit(1);
}

const text = `// Generated by scripts/snapshot-molen-primers.mjs from ${primers.source}.
// Do not edit by hand: change the primer in Molen and run the script again.

/** Teaches a model to write a molen/film@1 document. */
export const MOLEN_FILM_PRIMER: string = ${JSON.stringify(primers.film)};

/** Teaches a model to write a molen/game@1 document. */
export const MOLEN_GAME_PRIMER: string = ${JSON.stringify(primers.game)};

/** Teaches a model to write a data-only molen/scene@3 by hand. */
export const MOLEN_SCENE_PRIMER: string = ${JSON.stringify(primers.scene)};
`;

const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
// The source line names where the text came from; only the primers themselves must match.
const body = (s) => s.split('\n').slice(2).join('\n');
if (check) {
  if (body(current) !== body(text)) {
    console.error(`stale: ${out}; run node scripts/snapshot-molen-primers.mjs`);
    process.exit(1);
  }
  console.log(`molen primers match ${primers.source}`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} from ${primers.source}`);
}
