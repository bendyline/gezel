/** Refresh the shared preview assets, never an authored project's pages. */
import { copyFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import {
  injectPageDemo,
  pageDemoBootstrapSource,
} from '../packages/core/src/project-types/page-demo.js';
import { buildProjectPageTypography } from './project-page-typography.mjs';

const gilde = resolve(process.env.GILDE_DIR ?? '../gilde');
await writeFile(resolve(gilde, 'authoring/page-demo-bootstrap.js'), pageDemoBootstrapSource());
await writeFile(
  resolve(gilde, 'authoring/page-demo-injector.mjs'),
  `// Generated by Gezel's pages:sync-components.\nexport ${injectPageDemo.toString()}\n`,
);
await writeFile(
  resolve(gilde, 'authoring/page-demo-typography.css'),
  buildProjectPageTypography('packages/ui'),
);
for (const name of ['LICENSE-HankenGrotesk-OFL-1.1.txt', 'LICENSE-PTSerif-OFL-1.1.txt']) {
  await copyFile(resolve('packages/ui/src/assets/fonts', name), resolve(gilde, 'authoring', name));
}
console.log('Updated shared Gilde demo bootstrap and typography.');
